# Полные формы -> регулярные выражения, которые допускают и сокращённую форму.
WORD_FORMS = {"чтобы": "чтоб(?:ы)?", "бы": "б(?:ы)?"}


def unit_to_regex(unit):
    """«потому что» -> 'потому,? что'; «для того чтобы» -> 'для,? того,? чтоб(?:ы)?'."""
    words = [WORD_FORMS.get(word, re.escape(word)) for word in unit.split(" ")]
    return ",? ".join(words)  # между словами: необязательная запятая и пробел


def build_pattern(units):
    """Собирает регулярное выражение из множества единиц."""
    # Самые длинные единицы идут первыми:
    # регулярка берёт первый подошедший вариант, а не самый длинный.
    ordered = sorted(
        units, key=lambda unit: len(unit.lstrip(", ")), reverse=True
    )
    branches = []
    for unit in ordered:
        if unit.startswith(", "):
            # (?<=, ) — союз ищется только сразу после запятой с пробелом.
            branches.append(r"(?<=, )" + unit_to_regex(unit[2:]))
        else:
            # Граница слова слева. \b здесь не подходит:
            # он режет слова по дефису («кто-то» -> «то»).
            branches.append(r"(?<![\w-])" + unit_to_regex(unit))
    # Граница слова справа: после союза не должно быть ни буквы, ни дефиса.
    return re.compile("(?:" + "|".join(branches) + r")(?![\w-])")


pattern = build_pattern(conjunctions_set)


def normalize(text):
    """Приводит текст к виду, на который рассчитана регулярка."""
    text = text.lower().replace("ё", "е")
    # Все пробельные символы (пробелы, переносы строк, табуляции) -> один пробел,
    # иначе составные союзы не найдутся на стыке строк.
    text = re.sub(r"\s+", " ", text)
    # Перед запятой пробела нет, после запятой ровно один.
    return re.sub(r"\s*,\s*", ", ", text)


def find_conjunctions(text):
    """
    Возвращает список найденных союзов
    (в порядке появления в тексте), запятые внутри убраны.
    """
    return [match.group().replace(",", "")
            for match in pattern.finditer(normalize(text))]


