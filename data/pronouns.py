def build_pattern(units):
    """Собирает регулярное выражение из списка единиц."""
    # «ё» заменяем на «е» (в тексте это делается в find_pronouns), одинаковые после замены единицы склеиваем.
    normalized = {unit.replace('ё', 'е') for unit in units}
    # Граница слова: ни буквы, ни дефиса рядом. Так «то» не находится внутри «кто-то», а «все» — внутри «все-таки».
    return re.compile(r'(?<![\w-])(?:' + '|'.join(map(re.escape, by_length(normalized))) + r')(?![\w-])')


pattern = build_pattern(pronouns_list)


def find_pronouns(text, units_pattern=pattern):
    """Возвращает список найденных единиц (в порядке появления в тексте)."""
    # Все пробельные символы заменяем одним пробелом, иначе сочетания не найдутся на стыке строк.
    normalized = re.sub(r'\s+', ' ', text.lower().replace('ё', 'е'))
    return [match.group() for match in units_pattern.finditer(normalized)]


