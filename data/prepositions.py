def build_pattern(units):
    """Собирает регулярное выражение из списка единиц."""
    # Самые длинные единицы идут первыми: регулярка берёт первый подошедший вариант,
    # а не самый длинный, поэтому «в связи с» должно проверяться раньше, чем «в».
    ordered = sorted(units, key=len, reverse=True)
    # \b — граница слова; re.escape экранирует спецсимволы (например, дефис).
    return re.compile(r'\b(?:' + '|'.join(map(re.escape, ordered)) + r')\b')


pattern = build_pattern(prepositions_set)


def find_prepositions(text):
    """Возвращает список найденных предлогов (в порядке появления в тексте)."""
    # Все пробельные символы (пробелы, переносы строк, табуляции) заменяем одним пробелом,
    # иначе составные единицы не найдутся на стыке строк.
    normalized = re.sub(r'\s+', ' ', text).lower()
    return [match.group() for match in pattern.finditer(normalized)]


